// ─── 组件 ─────────────────────────────────────────────────

export function Tutorial() {
  const [activeSection, setActiveSection] = useState<string>('glossary')
  const [expandedSections, setExpandedSections] = useState<Set<string>>(new Set(['glossary']))
  const [searchQuery, setSearchQuery] = useState('')
  const contentRef = useRef<HTMLDivElement>(null)
  const sectionRefs = useRef<{ [key: string]: HTMLElement | null }>({})

  const trimmedQuery = searchQuery.trim()
  const filteredData = useMemo(() => filterSections(tutorialData, trimmedQuery), [trimmedQuery])

  // 滚动到指定章节
  const scrollToSection = (sectionId: string) => {
    setActiveSection(sectionId)
    const element = sectionRefs.current[sectionId]
    if (element && contentRef.current) {
      const containerTop = contentRef.current.getBoundingClientRect().top
      const elementTop = element.getBoundingClientRect().top
      const offset = elementTop - containerTop + contentRef.current.scrollTop - 20
      contentRef.current.scrollTo({ top: offset, behavior: 'smooth' })
    }
  }

  // 切换展开/折叠
  const toggleExpand = (sectionId: string) => {
    setExpandedSections(prev => {
      const newSet = new Set(prev)
      if (newSet.has(sectionId)) {
        newSet.delete(sectionId)
      } else {
        newSet.add(sectionId)
      }
      return newSet
    })
  }

  // 监听滚动更新当前章节
  useEffect(() => {
    const container = contentRef.current
    if (!container) return

    const handleScroll = () => {
      const containerTop = container.getBoundingClientRect().top
      let currentSection = 'glossary'

      Object.entries(sectionRefs.current).forEach(([id, element]) => {
        if (element) {
          const elementTop = element.getBoundingClientRect().top - containerTop
          if (elementTop <= 100) {
            currentSection = id
          }
        }
      })

      setActiveSection(currentSection)
    }

    container.addEventListener('scroll', handleScroll)
    return () => container.removeEventListener('scroll', handleScroll)
  }, [])

  // 渲染目录项
  const renderNavItem = (section: TutorialSection, level: number = 0) => {
    const Icon = section.icon || Circle
    const isActive = activeSection === section.id
    const hasChildren = section.children && section.children.length > 0
    // 搜索时强制展开，保证命中子章节可见
    const isExpanded = trimmedQuery ? true : expandedSections.has(section.id)

    return (
      <div key={section.id}>
        <div className="flex items-center">
          {hasChildren && (
            <button
              onClick={() => toggleExpand(section.id)}
              className="p-1 hover:bg-slate-100 dark:hover:bg-slate-700 rounded"
            >
              {isExpanded ? (
                <ChevronDown className="w-3 h-3 text-slate-400" />
              ) : (
                <ChevronRight className="w-3 h-3 text-slate-400" />
              )}
            </button>
          )}
          <button
            onClick={() => scrollToSection(section.id)}
            className={cn(
              'flex items-center gap-2 flex-1 px-2 py-1.5 text-sm rounded-md transition-colors text-left',
              !hasChildren && 'ml-5',
              level > 0 && 'text-xs',
              isActive
                ? 'bg-blue-50 text-blue-600 dark:bg-blue-900/20 dark:text-blue-400'
                : 'text-slate-600 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-slate-700'
            )}
          >
            <Icon className={cn('flex-shrink-0', level === 0 ? 'w-4 h-4' : 'w-3 h-3')} />
            <span className="truncate">{highlightText(section.title, trimmedQuery)}</span>
          </button>
        </div>
        {hasChildren && isExpanded && (
          <div className={cn('ml-4', level > 0 && 'ml-3')}>
            {section.children!.map(child => renderNavItem(child, level + 1))}
          </div>
        )}
      </div>
    )
  }

  // 渲染内容章节
  const renderContentSection = (section: TutorialSection, level: number = 0) => {
    const Icon = section.icon || Circle
    const HeadingTag = level === 0 ? 'h2' : level === 1 ? 'h3' : 'h4'
    const headingClass = level === 0
      ? 'text-xl font-bold text-blue-600 dark:text-blue-400'
      : level === 1
        ? 'text-lg font-semibold text-emerald-600 dark:text-emerald-400'
        : 'text-base font-medium text-slate-700 dark:text-slate-300'

    return (
      <div
        key={section.id}
        ref={el => { sectionRefs.current[section.id] = el }}
        className={cn('mb-6', level > 0 && 'ml-4')}
      >
        <HeadingTag className={cn('flex items-center gap-2 mb-2', headingClass)}>
          <Icon className={cn(level === 0 ? 'w-5 h-5' : 'w-4 h-4')} />
          {highlightText(section.title, trimmedQuery)}
          {section.important && (
            <span className="text-xs bg-red-100 text-red-600 dark:bg-red-900/30 dark:text-red-400 px-1.5 py-0.5 rounded font-normal">重要</span>
          )}
        </HeadingTag>

        {/* 概述 */}
        <p className="mb-3 text-sm text-slate-600 dark:text-slate-400 leading-relaxed">
          {section.description}
        </p>

        {/* 入口路径 */}
        {section.entry && (
          <p className="mb-3 text-xs text-slate-500 dark:text-slate-400 flex items-center gap-1">
            <MapPin className="w-3.5 h-3.5 flex-shrink-0 text-slate-400" />
            <span>入口：{highlightText(section.entry, trimmedQuery)}</span>
          </p>
        )}

        {/* 重要提示 */}
        {section.important && (
          <div className="mb-4 p-3 bg-red-50 dark:bg-red-900/20 border border-red-200 dark:border-red-800 rounded-lg">
            <p className="text-sm text-red-700 dark:text-red-300 font-medium">
              ⚠️ {section.important}
            </p>
          </div>
        )}

        {/* 操作步骤 */}
        {section.steps && section.steps.length > 0 && (
          <div className="mb-4">
            <h5 className="text-sm font-semibold text-slate-700 dark:text-slate-300 mb-2">📋 操作步骤</h5>
            <div className="space-y-3">
              {section.steps.map((step, i) => (
                <div key={i} className="flex gap-3">
                  <span className="flex-shrink-0 w-6 h-6 rounded-full bg-blue-100 dark:bg-blue-900/40 text-blue-600 dark:text-blue-400 text-xs font-bold flex items-center justify-center mt-0.5">
                    {i + 1}
                  </span>
                  <div className="min-w-0">
                    <p className="text-sm font-medium text-slate-700 dark:text-slate-300">{step.title}</p>
                    <div className="text-sm text-slate-500 dark:text-slate-400 leading-relaxed">
                      {renderStepContent(step.content)}
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* 使用技巧 */}
        {section.tips && section.tips.length > 0 && (
          <div className="mb-4 p-3 bg-blue-50 dark:bg-blue-900/20 border border-blue-200 dark:border-blue-800 rounded-lg">
            <p className="text-sm font-semibold text-blue-700 dark:text-blue-300 mb-1">💡 使用技巧</p>
            <ul className="space-y-1">
              {section.tips.map((tip, i) => (
                <li key={i} className="text-sm text-blue-600 dark:text-blue-400 flex items-start gap-2">
                  <span className="flex-shrink-0 mt-0.5">•</span>
                  {tip}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* 常见问题 */}
        {section.faq && section.faq.length > 0 && (
          <div className="mb-4 p-3 bg-amber-50 dark:bg-amber-900/20 border border-amber-200 dark:border-amber-800 rounded-lg">
            <p className="text-sm font-semibold text-amber-700 dark:text-amber-300 mb-1">❓ 常见问题</p>
            <dl className="space-y-2">
              {section.faq.map((item, i) => (
                <div key={i}>
                  <dt className="text-sm font-medium text-amber-700 dark:text-amber-300">Q: {item.q}</dt>
                  <dd className="text-sm text-amber-600 dark:text-amber-400 mt-0.5">A: {item.a}</dd>
                </div>
              ))}
            </dl>
          </div>
        )}

        {/* 子章节 */}
        {section.children?.map(child => renderContentSection(child, level + 1))}
      </div>
    )
  }

  return (
    <div className="h-full flex flex-col">
      {/* Header */}
      <div className="page-header flex-between mb-4">
        <div>
          <h1 className="page-title flex items-center gap-2">
            <BookOpen className="w-5 h-5" />
            使用教程
          </h1>
          <p className="page-description">详细了解系统各项功能的使用方法</p>
        </div>
        {/* 搜索框 */}
        <div className="relative w-64 max-w-full">
          <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
          <input
            className="input-ios pl-9"
            placeholder="搜索教程内容…"
            value={searchQuery}
            onChange={e => setSearchQuery(e.target.value)}
          />
        </div>
      </div>

      {/* Content */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        className="flex-1 flex gap-4 min-h-0"
      >
        {/* 左侧目录 */}
        <div className="w-72 flex-shrink-0 hidden lg:block">
          <div className="vben-card h-full overflow-hidden">
            <div className="vben-card-header">
              <h2 className="vben-card-title">目录</h2>
              {trimmedQuery && (
                <span className="badge-info">匹配 {filteredData.length} 个章节</span>
              )}
            </div>
            <div className="p-2 overflow-y-auto" style={{ height: 'calc(100% - 50px)' }}>
              {filteredData.length > 0 ? (
                filteredData.map(section => renderNavItem(section))
              ) : (
                <p className="text-sm text-slate-400 text-center py-8">
                  未找到与「{trimmedQuery}」相关的内容，换个关键词试试
                </p>
              )}
            </div>
          </div>
        </div>

        {/* 右侧内容 */}
        <div className="flex-1 min-w-0">
          <div className="vben-card h-full overflow-hidden">
            <div
              ref={contentRef}
              className="p-6 overflow-y-auto"
              style={{ height: 'calc(100vh - 180px)' }}
            >
              {filteredData.length > 0 ? (
                filteredData.map(section => renderContentSection(section))
              ) : (
                <div className="text-center py-16 text-slate-400">
                  <p className="text-3xl mb-2">🔍</p>
                  <p>未找到与「{trimmedQuery}」相关的内容</p>
                  <p className="text-xs mt-1">试试更短的关键词，如「批量导入」「版本」「备份」</p>
                </div>
              )}
            </div>
          </div>
        </div>
      </motion.div>
    </div>
  )
}

export default Tutorial
